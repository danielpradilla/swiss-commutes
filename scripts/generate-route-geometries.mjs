import { writeFile, rename } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { cities } from '../app/cities.ts';
import { decodePolyline, encodePolyline, routeKey } from '../app/route-geometry.ts';

const ROUTES_PER_CITY = 5;
const OUTPUT_PRECISION = 5;
const TRANSIT_TIME = '2026-09-02T07:00:00+02:00';
const USER_AGENT = 'swiss-commutes/0.1 (https://www.danielpradilla.info/swiss-commutes/)';

const wait = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));

function distanceKm(origin, target) {
  const latitude = (origin.lat + target.lat) * Math.PI / 360;
  return Math.hypot(
    (target.lat - origin.lat) * 111.2,
    (target.lon - origin.lon) * 111.2 * Math.cos(latitude),
  );
}

function visibleCorridors(corridors) {
  const primary = new Map();
  corridors.forEach((corridor, index) => {
    const code = corridor.direction === 'inbound' ? corridor.origin.code : corridor.target.code;
    const current = primary.get(code);
    if (current === undefined || corridors[current].commuters < corridor.commuters) primary.set(code, index);
  });
  return corridors.filter((corridor, index) => {
    const code = corridor.direction === 'inbound' ? corridor.origin.code : corridor.target.code;
    return Math.floor(corridor.commuters / 900) + (primary.get(code) === index ? 1 : 0) > 0;
  });
}

function selectPreviewCorridors(corridors) {
  const visible = visibleCorridors(corridors).sort((a, b) => b.commuters - a.commuters);
  const selected = new Set(visible.slice(0, ROUTES_PER_CITY));
  for (const mode of ['car', 'transit', 'soft']) {
    const first = visible.find((corridor) => corridor.mode === mode);
    if (first) selected.add(first);
  }
  return [...selected];
}

async function valhallaRoute(corridor) {
  const costing = corridor.mode === 'car'
    ? 'auto'
    : distanceKm(corridor.origin, corridor.target) <= 6 ? 'pedestrian' : 'bicycle';
  const request = JSON.stringify({
    locations: [corridor.origin, corridor.target].map(({ lat, lon }) => ({ lat, lon })),
    costing,
    directions_options: { units: 'kilometers' },
  });
  const url = new URL('https://valhalla1.openstreetmap.de/route');
  url.searchParams.set('json', request);
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT }, signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw new Error(`Valhalla ${response.status}`);
  const result = await response.json();
  return result.trip.legs.flatMap((leg) => decodePolyline(leg.shape, 6));
}

async function transitRoute(corridor) {
  const url = new URL('https://api.transitous.org/api/v6/plan');
  url.searchParams.set('fromPlace', `${corridor.origin.lat},${corridor.origin.lon}`);
  url.searchParams.set('toPlace', `${corridor.target.lat},${corridor.target.lon}`);
  url.searchParams.set('time', TRANSIT_TIME);
  url.searchParams.set('numItineraries', '1');
  url.searchParams.set('maxItineraries', '1');
  url.searchParams.set('detailedLegs', 'true');
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT }, signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`Transitous ${response.status}`);
  const result = await response.json();
  const itinerary = result.itineraries?.[0];
  if (!itinerary) throw new Error('Transitous returned no itinerary');
  return itinerary.legs.flatMap((leg) => leg.legGeometry?.points
    ? decodePolyline(leg.legGeometry.points, leg.legGeometry.precision ?? 6)
    : []);
}

export async function generate(output = new URL('../app/data/route-geometries.ts', import.meta.url)) {
  const generated = {};
  let attempted = 0;
  for (const city of cities) {
    const selected = selectPreviewCorridors(city.data.corridors);
    for (const corridor of selected) {
      attempted += 1;
      const key = routeKey(city.slug, corridor);
      try {
        const routed = corridor.mode === 'transit' ? await transitRoute(corridor) : await valhallaRoute(corridor);
        if (routed.length < 2 || routed.some(p => p.length !== 2 || !p.every(Number.isFinite))) throw new Error('Invalid preview geometry');
        const points = [
          [corridor.origin.lat, corridor.origin.lon],
          ...routed,
          [corridor.target.lat, corridor.target.lon],
        ];
        generated[key] = encodePolyline(points, OUTPUT_PRECISION);
        process.stdout.write(`\r${attempted} requests, ${Object.keys(generated).length} routes`);
      } catch (error) {
        throw new Error(`Preview refresh failed for ${key}; previous cache preserved`, { cause: error });
      }
      await wait(350);
    }
  }

  const source = `// Generated by \`npm run routes:preview\`.\nexport const routeGeometries: Record<string, string> = ${JSON.stringify(generated, null, 2)};\n`;
  const temporary = new URL(`${output.href}.tmp`);
  await writeFile(temporary, source);
  await rename(temporary, output);
  process.stdout.write(`\nWrote ${Object.keys(generated).length} preview routes.\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await generate();
